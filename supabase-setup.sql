-- =====================================================
-- COIVI.TN - SUPABASE DATABASE SETUP
-- Creates rides and user roles
-- Run this script on a NEW Supabase project
-- =====================================================

-- 1. RIDES / TRAJETS
create table if not exists public.rides (
    id bigint generated by default as identity primary key,
    departure text not null,
    destination text not null,
    departure_time timestamptz not null,
    available_seats integer not null check (available_seats >= 0),
    price_per_passenger numeric(10,2) not null check (price_per_passenger >= 0),
    description text,
    driver_name text,
    is_available boolean not null default true,
    created_at timestamptz not null default now()
);

-- 2. USER ROLES
create table if not exists public.user_roles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    role text not null default 'client'
        check (role in ('client', 'admin')),
    created_at timestamptz not null default now()
);

-- =====================================================
-- ROW LEVEL SECURITY
-- =====================================================

alter table public.rides enable row level security;
alter table public.user_roles enable row level security;

-- Visitors and logged-in users can see available rides.
create policy "Anyone can view available rides"
on public.rides
for select
using (is_available = true);

-- A logged-in user can read only their own role.
create policy "Users can view their own role"
on public.user_roles
for select
to authenticated
using (auth.uid() = user_id);

-- =====================================================
-- PERMISSIONS
-- =====================================================

grant select on public.rides to anon, authenticated;
grant select on public.user_roles to authenticated;

-- Required for the identity sequence used by rides.
grant usage, select on sequence public.rides_id_seq to authenticated;