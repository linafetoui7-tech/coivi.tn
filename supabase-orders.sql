-- =====================================================
-- COIVI.TN - RESERVATIONS
-- Connects users to rides they reserve
-- =====================================================

-- 1. RESERVATIONS TABLE
create table if not exists public.reservations (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references auth.users(id)
        on delete cascade,

    ride_id bigint not null
        references public.rides(id)
        on delete cascade,

    seats_reserved integer not null default 1
        check (seats_reserved > 0),

    total_price numeric(10,2) not null
        check (total_price >= 0),

    status text not null default 'confirmed'
        check (status in ('pending', 'confirmed', 'cancelled')),

    created_at timestamptz not null default now()
);

-- =====================================================
-- ROW LEVEL SECURITY
-- =====================================================

alter table public.reservations enable row level security;

-- Users can see only their own reservations.
create policy "Users can view their own reservations"
on public.reservations
for select
to authenticated
using (auth.uid() = user_id);

-- Users can create reservations only for themselves.
create policy "Users can create their own reservations"
on public.reservations
for insert
to authenticated
with check (auth.uid() = user_id);

-- Users can update only their own reservations.
create policy "Users can update their own reservations"
on public.reservations
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- =====================================================
-- PERMISSIONS
-- =====================================================

grant select, insert, update
on public.reservations
to authenticated;

grant usage, select
on sequence public.reservations_id_seq
to authenticated;